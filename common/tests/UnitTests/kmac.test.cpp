TEST_P(KmacComplianceTest, MatchesNistVector) {
  // Get the data for the current test iteration
  const auto& [variant, key, data, custom, expected, xof] = GetParam();

  std::vector<uint8_t> out(expected.size());

  ASSERT_NO_THROW(derive(variant, key, custom, data, out, xof));

  EXPECT_EQ(out, expected) << "KMAC output did not match NIST vector";
}
